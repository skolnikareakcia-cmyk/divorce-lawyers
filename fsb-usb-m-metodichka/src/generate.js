// docx-js присваивает всем закладкам w:id="1" — Word требует уникальные id, перенумеровываем
async function fixBookmarkIds(buf) {
  const JSZip = require("jszip");
  const zip = await JSZip.loadAsync(buf, { createFolders: false });
  let xml = await zip.file("word/document.xml").async("string");
  let n = 0;
  xml = xml.replace(/<w:bookmarkStart w:name="([^"]+)" w:id="\d+"\/>([\s\S]*?)<w:bookmarkEnd w:id="\d+"\/>/g,
    (_, name, inner) => { n += 1; return `<w:bookmarkStart w:name="${name}" w:id="${n}"/>${inner}<w:bookmarkEnd w:id="${n}"/>`; });
  zip.file("word/document.xml", xml);
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}

